-- V1: baseline schema (generated from the JPA entities; adopted as-is by pre-existing databases)

create table api_keys (
    created_at timestamp(6),
    id bigint generated by default as identity,
    user_id bigint not null,
    key_value varchar(255) not null unique,
    name varchar(255) not null,
    primary key (id)
);

create table password_reset_tokens (
    created_at timestamp(6) not null,
    expires_at timestamp(6) not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    token varchar(255) not null unique,
    primary key (id)
);

create table refresh_tokens (
    expires_at timestamp(6) not null,
    id bigint generated by default as identity,
    user_id bigint not null,
    token varchar(255) not null unique,
    primary key (id)
);

create table tags (
    id bigint generated by default as identity,
    user_id bigint not null,
    name varchar(255) not null,
    primary key (id)
);

create table url_clicks (
    clicked_at timestamp(6),
    id bigint generated by default as identity,
    url_id bigint not null,
    browser varchar(255),
    city varchar(255),
    country varchar(255),
    device_type varchar(255),
    ip_hash varchar(255),
    operating_system varchar(255),
    referrer varchar(255),
    primary key (id)
);

create table url_tags (
    tag_id bigint not null,
    url_id bigint not null,
    primary key (tag_id, url_id)
);

create table urls (
    is_active boolean not null,
    is_archived boolean not null,
    is_deleted boolean,
    is_favorite boolean not null,
    is_one_time boolean not null,
    click_count bigint not null,
    created_at timestamp(6),
    expires_at timestamp(6),
    id bigint generated by default as identity,
    updated_at timestamp(6),
    user_id bigint,
    short_code varchar(20) not null unique,
    custom_alias varchar(50),
    description TEXT,
    original_url TEXT not null,
    password_hash varchar(255),
    title varchar(255),
    visibility varchar(255) not null check (visibility in ('PUBLIC','PRIVATE')),
    primary key (id)
);

create table users (
    is_verified boolean not null,
    created_at timestamp(6),
    id bigint generated by default as identity,
    updated_at timestamp(6),
    email varchar(255) not null unique,
    name varchar(255) not null,
    password varchar(255) not null,
    profile_image varchar(255),
    role varchar(255) not null check (role in ('USER','ADMIN')),
    primary key (id)
);

create index idx_refresh_token_user
   on refresh_tokens (user_id);

create index idx_tag_user
   on tags (user_id);

create index idx_url_click_url
   on url_clicks (url_id);

create index idx_url_click_url_clicked_at
   on url_clicks (url_id, clicked_at);

create index idx_url_user
   on urls (user_id);

