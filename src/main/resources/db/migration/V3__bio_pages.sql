-- Link-in-bio pages: a public page at /p/{slug} listing a user's links.
-- Each item points at a normal Linky short link, so clicks on a page are tracked by the
-- existing analytics pipeline.
create table bio_pages (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users (id),
    slug varchar(40) not null unique,
    title varchar(100) not null,
    bio varchar(300),
    created_at timestamp(6),
    updated_at timestamp(6)
);

create index idx_bio_page_user on bio_pages (user_id);

create table bio_page_links (
    id bigint generated by default as identity primary key,
    page_id bigint not null references bio_pages (id) on delete cascade,
    label varchar(100) not null,
    short_code varchar(20) not null,
    original_url text not null,
    position integer not null
);

create index idx_bio_link_page on bio_page_links (page_id);
