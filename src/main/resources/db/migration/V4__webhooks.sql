-- Webhooks: user-registered HTTPS endpoints that receive signed events.
-- webhook_deliveries is a transactional outbox: an event is written in the same transaction as the
-- change that caused it, and a background worker delivers it with retries and backoff.
create table webhooks (
    id bigint generated by default as identity primary key,
    user_id bigint not null references users (id),
    url varchar(2048) not null,
    secret varchar(64) not null,
    events varchar(200) not null,
    active boolean not null,
    consecutive_failures integer not null,
    disabled_reason varchar(200),
    created_at timestamp(6)
);

create index idx_webhook_user on webhooks (user_id);

create table webhook_deliveries (
    id bigint generated by default as identity primary key,
    webhook_id bigint not null references webhooks (id) on delete cascade,
    event varchar(50) not null,
    payload text not null,
    status varchar(12) not null,
    attempts integer not null,
    next_attempt_at timestamp(6) not null,
    last_status_code integer,
    last_error varchar(300),
    created_at timestamp(6),
    delivered_at timestamp(6)
);

-- the worker polls "pending and due"; the partial index keeps that scan tiny as history grows
create index idx_webhook_delivery_due on webhook_deliveries (next_attempt_at) where status = 'PENDING';
create index idx_webhook_delivery_webhook on webhook_deliveries (webhook_id, id desc);
